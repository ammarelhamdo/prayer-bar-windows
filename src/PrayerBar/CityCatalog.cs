using System.Globalization;
using System.IO;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace PrayerBar;

/// <summary>A city from the catalog. Coordinates and time zone drive both the API request and
/// the offline calculation, so no geocoding is needed at runtime.</summary>
public sealed class City
{
    [JsonPropertyName("en")] public string En { get; set; } = "";
    [JsonPropertyName("ar")] public string Ar { get; set; } = "";
    [JsonPropertyName("lat")] public double Lat { get; set; }
    [JsonPropertyName("lng")] public double Lng { get; set; }
    [JsonPropertyName("tz")] public string Tz { get; set; } = "";

    public string Name(bool arabic) => arabic && Ar.Length > 0 ? Ar : En;
}

public sealed class Country
{
    [JsonPropertyName("code")] public string Code { get; set; } = "";
    [JsonPropertyName("en")] public string En { get; set; } = "";
    [JsonPropertyName("ar")] public string Ar { get; set; } = "";

    /// <summary>Aladhan method used by default for this country (Turkey = 13 / Diyanet).</summary>
    [JsonPropertyName("method")] public int Method { get; set; } = 3;

    [JsonPropertyName("cities")] public List<City> Cities { get; set; } = new();

    public string Name(bool arabic) => arabic && Ar.Length > 0 ? Ar : En;
}

/// <summary>
/// The country -> city list. Ships inside the exe as <c>Data/cities.json</c> (generated by
/// tools/build_cities.py from GeoNames + Wikidata + Aladhan) so it works offline.
/// A user file at <c>%AppData%\PrayerBar\cities.json</c> with the same shape is merged on top:
/// new countries are added, existing countries get extra/replaced cities (matched by English name),
/// and a non-zero "method" overrides the country default.
/// </summary>
public sealed class CityCatalog
{
    private sealed class FileShape
    {
        [JsonPropertyName("countries")] public List<Country> Countries { get; set; } = new();
    }

    public IReadOnlyList<Country> Countries { get; }

    public static string UserFilePath => Path.Combine(AppSettings.DataDir, "cities.json");

    private CityCatalog(List<Country> countries) => Countries = countries;

    private static CityCatalog? _instance;

    /// <summary>Loaded once on first use (about 1 ms per 1,000 cities).</summary>
    public static CityCatalog Instance => _instance ??= Load();

    /// <summary>Re-reads the bundled and user files (after the user edits their cities.json).</summary>
    public static void Reload() => _instance = Load();

    private static CityCatalog Load()
    {
        var countries = new List<Country>();
        using (var stream = typeof(CityCatalog).Assembly.GetManifestResourceStream("PrayerBar.Data.cities.json"))
        {
            if (stream != null)
                countries = JsonSerializer.Deserialize<FileShape>(stream)?.Countries ?? new();
        }

        try
        {
            if (File.Exists(UserFilePath))
            {
                var extra = JsonSerializer.Deserialize<FileShape>(File.ReadAllText(UserFilePath))?.Countries;
                if (extra != null) Merge(countries, extra);
            }
        }
        catch (Exception ex)
        {
            PrayerService.Log($"User cities.json ignored: {ex.Message}");
        }

        countries.Sort((a, b) => string.Compare(a.En, b.En, StringComparison.OrdinalIgnoreCase));
        return new CityCatalog(countries);
    }

    private static void Merge(List<Country> target, List<Country> extra)
    {
        foreach (var add in extra)
        {
            var existing = target.FirstOrDefault(c => c.Code.Equals(add.Code, StringComparison.OrdinalIgnoreCase));
            if (existing == null)
            {
                target.Add(add);
                continue;
            }
            if (add.Method != 0 && add.Method != 3) existing.Method = add.Method;
            foreach (var city in add.Cities)
            {
                existing.Cities.RemoveAll(c => c.En.Equals(city.En, StringComparison.OrdinalIgnoreCase));
                existing.Cities.Insert(0, city); // user cities first
            }
        }
    }

    public Country? FindCountry(string code) =>
        Countries.FirstOrDefault(c => c.Code.Equals(code, StringComparison.OrdinalIgnoreCase));

    public City? FindCity(string countryCode, string cityEn) =>
        FindCountry(countryCode)?.Cities.FirstOrDefault(c => c.En.Equals(cityEn, StringComparison.OrdinalIgnoreCase));

    /// <summary>
    /// Folds text for search: lower-case, no Latin diacritics (Şanlıurfa ~ sanliurfa), and Arabic
    /// letter variants unified (أ/إ/آ -> ا, ة -> ه, ى -> ي, no tashkeel or tatweel), so either
    /// language matches regardless of how the user types it.
    /// </summary>
    public static string Fold(string text)
    {
        var decomposed = text.ToLowerInvariant().Normalize(NormalizationForm.FormD);
        var sb = new StringBuilder(decomposed.Length);
        foreach (var ch in decomposed)
        {
            var cat = CharUnicodeInfo.GetUnicodeCategory(ch);
            if (cat == UnicodeCategory.NonSpacingMark) continue;           // Latin accents, Arabic harakat
            switch (ch)
            {
                case 'ı': sb.Append('i'); break;                             // Turkish dotless i
                case 'أ' or 'إ' or 'آ' or 'ٱ': sb.Append('ا'); break;
                case 'ة': sb.Append('ه'); break;
                case 'ى': sb.Append('ي'); break;
                case 'ـ': break;                                             // tatweel
                default: sb.Append(ch); break;
            }
        }
        return sb.ToString().Normalize(NormalizationForm.FormC);
    }
}
